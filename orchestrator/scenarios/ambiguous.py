"""
Ambiguous requirement scenario: "Add analytics to our URL shortener."

Why this requirement is deliberately ambiguous
──────────────────────────────────────────────
The raw text ("Add analytics to our URL shortener") contains at least
seven business decisions that cannot be resolved by engineering alone:

  1. Metric scope — clicks only?  unique visitors?  geographic?  device?
  2. Access control — owner-only?  all authenticated users?  public?
  3. Data retention — 7 days?  90 days?  indefinite?
  4. Processing model — real-time (synchronous)?  async background?
  5. Interface type — REST API only?  also a UI dashboard?
  6. Redirect SLA — must the <50ms redirect guarantee be preserved?
  7. Privacy / GDPR — raw IP storage allowed?  or only hashed?

The agentic system MUST:
  • Detect every ambiguity before proposing any implementation.
  • Generate precise, answerable clarification questions.
  • Record the human's answer as an explicit Decision (made_by="human").
  • Never silently invent a business requirement.
  • Re-plan affected tasks after every clarification answer.
  • Produce an assumption registry distinguishing confirmed vs assumed scope.

Execution trace
───────────────
  Requirement
      ↓ AmbiguityDetectionStage
  Ambiguity catalogue + clarification questions
      ↓ ClarificationStage  [PAUSES — calls ClarificationGateway]
  Human answers → recorded as Decisions
      ↓ RequirementNormalizationStage
  Definitive normalised requirement + assumption registry
      ↓ TaskPlanningStage
  Task plan showing tasks added/excluded by each answer
      ↓ ValidationStage  [requires human approval]
  Validation: zero silent inventions confirmed

ClarificationGateway
────────────────────
Production: HumanClarificationGateway blocks the async event loop until
            answers are submitted via the operator UI or API.
Testing:    PresetClarificationGateway returns pre-configured answers
            immediately.  Use DefaultAnswerGateway to test the "safe defaults
            path" where some questions are unanswered.

Public API
──────────
    ClarificationQuestion
    ClarificationAnswer
    ClarificationGateway (ABC)
    PresetClarificationGateway
    DefaultAnswerGateway

    create_ambiguous_requirement()  → Requirement
    create_ambiguous_workflow()     → WorkflowDefinition
    create_ambiguous_stages(gw)     → dict[str, BaseStage]
    run_ambiguous_scenario(gw, ...) → WorkflowState  (async)
"""
