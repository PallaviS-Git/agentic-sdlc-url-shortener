DEFAULT_REQUIREMENT_TEXT = (
    "Add analytics to our URL shortener."
)

"""
The deliberately minimal requirement above contains no specifics about:
  what to track, who sees it, how long to keep it, whether it affects
  redirect performance, or how to present the data.

This tests the system's ability to detect and surface ambiguity rather
than silently filling in the gaps.
"""


# ─── Clarification models ─────────────────────────────────────────────────────


def _now() -> datetime:
    return datetime.now(tz=timezone.utc)


class ClarificationQuestion(BaseModel):
    """A single question generated by ambiguity detection and posed to a human."""

    id: str = Field(description="Machine-readable question identifier (e.g. 'Q1')")
    question: str = Field(description="The specific question posed to the human")
    context: str = Field(description="Why this question matters for the engineering requirement")
    options: list[str] | None = Field(
        default=None,
        description="If multiple-choice: the available options",
    )
    default: str | None = Field(
        default=None,
        description=(
            "Safe engineering default if human does not answer. "
            "Must be the most conservative option, not an arbitrary guess."
        ),
    )
    impact: str = Field(
        description="Which downstream tasks or decisions depend on this answer"
    )
    ambiguity_id: str = Field(description="ID of the AmbiguityItem this question resolves")


class ClarificationAnswer(BaseModel):
    """A human's response to a ClarificationQuestion."""

    question_id: str
    answer: str
    answered_by: str = Field(default="human", description="'human' or 'default' (safe fallback)")
    answered_at: datetime = Field(default_factory=_now)
    notes: str = Field(default="", description="Optional notes from the human")


class ClarificationRecord(BaseModel):
    """Immutable pairing of a question with its answer — the atomic clarification unit."""

    question: ClarificationQuestion
    answer: ClarificationAnswer

    @property
    def was_human_answered(self) -> bool:
        return self.answer.answered_by == "human"

    @property
    def question_id(self) -> str:
        return self.question.id


# ─── ClarificationGateway ─────────────────────────────────────────────────────


class ClarificationGateway(ABC):
    """
    Abstract gateway for obtaining human answers to clarification questions.

    In production, implementations block the coroutine until a human submits
    answers via an operator UI or API endpoint.  In tests, implementations
    return pre-configured answers immediately.

    No answer may be fabricated — every answer must come from a human or
    be an explicit, documented safe default.
    """

    @abstractmethod
    async def clarify(
        self, questions: list[ClarificationQuestion]
    ) -> list[ClarificationAnswer]:
        """
        Present questions to a human (or return pre-configured answers for tests).

        Implementations MUST return one ClarificationAnswer per question.
        For unanswered questions, use the question's ``default`` value with
        ``answered_by="default"``.

        Args:
            questions: The clarification questions to present.

        Returns:
            One ClarificationAnswer per input question.
        """
        ...

    def __repr__(self) -> str:
        return f"{self.__class__.__name__}()"


class PresetClarificationGateway(ClarificationGateway):
    """
    Test gateway that returns pre-configured answers immediately.

    Use ``answers`` to simulate a specific human decision path.
    Any question without a preset answer receives the question's safe default.

    Example::

        gateway = PresetClarificationGateway(answers={
            "Q1": "clicks, unique visitors, country",
            "Q2": "URL owner only",
            "Q7": "hashed IP (SHA-256)",
        })
    """

    def __init__(self, answers: dict[str, str]) -> None:
        self._answers = answers

    async def clarify(
        self, questions: list[ClarificationQuestion]
    ) -> list[ClarificationAnswer]:
        now = _now()
        return [
            ClarificationAnswer(
                question_id=q.id,
                answer=self._answers.get(q.id, q.default or "not specified"),
                answered_by="human" if q.id in self._answers else "default",
                answered_at=now,
                notes=(
                    "Preset answer (test)"
                    if q.id in self._answers
                    else f"Defaulted to safe value: '{q.default}'"
                ),
            )
            for q in questions
        ]


class DefaultAnswerGateway(ClarificationGateway):
    """
    Gateway that uses every question's safe default answer.

    Useful for testing the 'no human input' path and verifying that the
    system still produces a coherent (if conservative) normalised requirement.
    """

    async def clarify(
        self, questions: list[ClarificationQuestion]
    ) -> list[ClarificationAnswer]:
        now = _now()
        return [
            ClarificationAnswer(
                question_id=q.id,
                answer=q.default or "not specified",
                answered_by="default",
                answered_at=now,
                notes=f"Safe default applied (no human response): '{q.default}'",
            )
            for q in questions
        ]


# ─── Stage helpers ────────────────────────────────────────────────────────────


def _artifact(
    name: str,
    artifact_type: ArtifactType,
    stage: str,
    content: dict[str, Any] | str,
) -> Artifact:
    body = json.dumps(content, indent=2) if isinstance(content, dict) else content
    return Artifact(name=name, artifact_type=artifact_type,
                    produced_by_stage=stage, content=body)


def _decision(
    title: str,
    description: str,
    rationale: str,
    decision_type: DecisionType,
    stage: str,
    made_by: str = "orchestrator",
    parent_id: str | None = None,
    downstream_impacts: list[str] | None = None,
) -> Decision:
    return Decision(
        decision_type=decision_type,
        title=title,
        description=description,
        rationale=rationale,
        stage=stage,
        made_by=made_by,
        parent_decision_id=parent_id,
        downstream_impacts=downstream_impacts or [],
    )


def _task(title: str, description: str, stage: str, agent: str, rationale: str = "") -> Task:
    return Task(
        title=title,
        description=description,
        status=TaskStatus.COMPLETED,
        stage=stage,
        assigned_agent=agent,
        rationale=rationale or f"Required by {stage} stage",
    )


def _val(
    rule: str,
    passed: bool,
    message: str,
    stage: str,
    severity: ValidationSeverity = ValidationSeverity.ERROR,
    evidence: dict[str, Any] | None = None,
) -> ValidationResult:
    return ValidationResult(rule_name=rule, passed=passed, severity=severity,
                            message=message, stage=stage, evidence=evidence or {})


