def create_ambiguous_requirement(
    raw_text: str = DEFAULT_REQUIREMENT_TEXT,
) -> Requirement:
    """Build the ambiguous Requirement for the analytics scenario."""
    return Requirement(
        title="Add Analytics to URL Shortener — Ambiguous Requirement",
        raw_text=raw_text,
        requirement_type=RequirementType.AMBIGUOUS,
        ambiguities=[
            AmbiguityItem(field=f, description=d)
            for f, d in [
                ("analytics_metrics", "What data to collect is unspecified"),
                ("access_control", "Who may read analytics is unspecified"),
                ("data_retention", "How long to keep data is unspecified"),
                ("processing_model", "Sync vs async recording is unspecified"),
                ("interface_type", "API vs UI is unspecified"),
                ("redirect_sla", "SLA impact is unspecified"),
                ("privacy_compliance", "IP storage policy is unspecified"),
            ]
        ],
    )


def create_ambiguous_workflow() -> WorkflowDefinition:
    """Build the linear DAG for the ambiguous analytics scenario."""
    return WorkflowDefinition(
        name="ambiguous_analytics",
        description="Ambiguous requirement: 'Add analytics to URL shortener' — detect, clarify, normalise, plan, validate",
        version="1.0.0",
        stages=[
            "ambiguity_detection",
            "clarification",
            "normalization",
            "task_planning",
            "validation",
        ],
        dependencies=[
            StageDependency(from_stage="ambiguity_detection", to_stage="clarification"),
            StageDependency(from_stage="clarification",        to_stage="normalization"),
            StageDependency(from_stage="normalization",        to_stage="task_planning"),
            StageDependency(from_stage="task_planning",        to_stage="validation"),
        ],
    )


def create_ambiguous_stages(
    clarification_gateway: ClarificationGateway | None = None,
) -> dict[str, BaseStage]:
    """Instantiate all stage implementations for the ambiguous scenario."""
    gw = clarification_gateway or PresetClarificationGateway(DEFAULT_PRESET_ANSWERS)
    return {
        "ambiguity_detection": AmbiguityDetectionStage(),
        "clarification":       ClarificationStage(gateway=gw),
        "normalization":       RequirementNormalizationStage(),
        "task_planning":       TaskPlanningStage(),
        "validation":          AmbiguousValidationStage(),
    }


async def run_ambiguous_scenario(
    raw_requirement: str = DEFAULT_REQUIREMENT_TEXT,
    clarification_gateway: ClarificationGateway | None = None,
    approval_gateway: ApprovalGateway | None = None,
    policy_engine: PolicyEngine | None = None,
) -> "WorkflowState":  # type: ignore[name-defined]
    """
    Run the full ambiguous analytics scenario.

    Args:
        raw_requirement:        Raw ambiguous requirement text.
        clarification_gateway:  Gateway for human clarification answers.
                                Defaults to PresetClarificationGateway with
                                DEFAULT_PRESET_ANSWERS.
        approval_gateway:       Gateway for final human approval (validation stage).
                                Defaults to AutoApproveGateway.
        policy_engine:          Optional governance PolicyEngine.

    Returns:
        WorkflowState after the pipeline completes.
    """
    from orchestrator.core.autonomy import AutoApproveGateway

    requirement = create_ambiguous_requirement(raw_requirement)
    definition = create_ambiguous_workflow()
    stages = create_ambiguous_stages(clarification_gateway)

    engine = WorkflowEngine(
        definition=definition,
        stages=stages,
        approval_gateway=approval_gateway or AutoApproveGateway(),
        policy_engine=policy_engine,
    )
    return await engine.run(requirement)
