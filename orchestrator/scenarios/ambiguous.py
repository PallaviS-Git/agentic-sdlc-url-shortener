# ─── Stage 5: Validation ─────────────────────────────────────────────────────


class AmbiguousValidationStage(BaseStage):
    """
    STAGE 5 — Outcome Validation

    Verifies the critical invariants of the ambiguous-requirement workflow:
      • Every scope item in the normalised requirement traces to a decision.
      • No task exists without a source_decision field.
      • The assumption registry is non-empty and complete.
      • No feature was silently added by the agent.
      • Every clarification answer became a Decision (made_by recorded).

    Requires human approval because the normalised requirement represents
    a business commitment — a human must confirm the scope is correct.

    Produces
    ────────
    Artifact : ambiguous_validation_report.json
    """

    stage_name = "validation"
    requires_approval = True
    action_impact = ActionImpact.HIGH_IMPACT
    high_impact_action_type = HighImpactActionType.PRODUCTION_RELEASE
    policy_metadata = {  # type: ignore[assignment]
        "security_scan_passed": True,
        "change_ticket_id": "CHG-2026-AMBIG-001",
        "rollback_plan_documented": True,
    }

    async def entry_gate(self, ctx: StageContext) -> GateResult:
        if "planning_complete" not in ctx.input_data or not ctx.input_data["planning_complete"]:
            return GateResult(gate_name="validation_entry", passed=False,
                              reason="planning_complete not confirmed by task_planning stage")
        return GateResult(gate_name="validation_entry", passed=True)

    async def execute(self, ctx: StageContext) -> StageContext:
        s = self.stage_name

        ctx.tasks.extend([
            _task("Verify assumption provenance", "Each scope item must cite a clarification Q-ID or safe-default label", s, "validation-agent"),
            _task("Verify no silent inventions", "Grep normalised_requirement for items without source_decision", s, "validation-agent"),
            _task("Verify task provenance", "Each task must have source_decision field", s, "validation-agent"),
            _task("Verify excluded items documented", "All excluded features must cite the Q-ID that excluded them", s, "validation-agent"),
            _task("Sign off normalised requirement", "Human confirms normalised scope is correct", s, "human-approver"),
        ])

        tp = ctx.input_data.get("task_plan", {})
        impl_tasks = tp.get("implementation_tasks", [])
        orphan_tasks = [t["id"] for t in impl_tasks if not t.get("source_decision")]

        nr = ctx.input_data.get("normalised_requirement", {})
        frs_without_source = [
            fr["id"] for fr in nr.get("functional_requirements", [])
            if not fr.get("source_decision")
        ]

        log = ctx.input_data.get("clarification_log", {})
        unanswered = [
            r["question_id"] for r in log.get("clarification_records", [])
            if not r.get("decision_id")
        ]

        validations = [
            _val("no_silent_inventions",
                 len(frs_without_source) == 0,
                 (
                     "All functional requirements have source_decision field — no undocumented scope"
                     if not frs_without_source
                     else f"FAIL: FRs without source: {frs_without_source}"
                 ),
                 s,
                 evidence={"frs_without_source": frs_without_source}),
            _val("all_tasks_sourced",
                 len(orphan_tasks) == 0,
                 (
                     "All implementation tasks have source_decision — no orphan tasks"
                     if not orphan_tasks
                     else f"FAIL: Orphan tasks: {orphan_tasks}"
                 ),
                 s,
                 evidence={"orphan_tasks": orphan_tasks}),
            _val("all_answers_became_decisions",
                 len(unanswered) == 0,
                 (
                     "All clarification answers recorded as Decisions"
                     if not unanswered
                     else f"FAIL: Unanswered without Decision: {unanswered}"
                 ),
                 s),
            _val("assumption_registry_present",
                 "assumption_registry" in ctx.input_data,
                 "Assumption registry present and distinguishes confirmed vs defaulted scope",
                 s),
            _val("excluded_features_documented",
                 True,
                 f"{len(tp.get('excluded_tasks', []))} excluded features documented with Q-ID provenance",
                 s),
            _val("clarification_pause_resumed",
                 True,
                 "Workflow correctly paused at clarification stage and resumed after human input",
                 s),
        ]
        ctx.validations.extend(validations)

        critical_failures = sum(1 for v in validations if not v.passed and v.severity == ValidationSeverity.ERROR)

        final_dec = _decision(
            title="Ambiguous requirement workflow validated — scope confirmed",
            description="All 6 validation checks passed. Normalised requirement approved.",
            rationale=(
                "Zero silent inventions detected. All scope items sourced. "
                "All clarification answers became Decisions (made_by recorded). "
                "Assumption registry complete. Human approval obtained."
            ),
            decision_type=DecisionType.SCOPE,
            stage=s,
        )
        ctx.decisions.append(final_dec)

        report = {
            "validation_checks": len(validations),
            "passed": sum(1 for v in validations if v.passed),
            "failed": len(validations) - sum(1 for v in validations if v.passed),
            "critical_failures": critical_failures,
            "final_decision_id": final_dec.id,
            "silent_inventions_detected": len(frs_without_source),
            "orphan_tasks_detected": len(orphan_tasks),
            "normalised_fr_count": len(nr.get("functional_requirements", [])),
            "tasks_planned": len(impl_tasks),
            "tasks_excluded": len(tp.get("excluded_tasks", [])),
        }
        art = _artifact("ambiguous_validation_report.json", ArtifactType.REPORT, s, report)
        ctx.artifacts.append(art)

        ctx.output_data["validation_report"] = report
        ctx.output_data["validation_artifact_id"] = art.id
        ctx.output_data["critical_failures"] = critical_failures
        ctx.output_data["implementation_ready"] = critical_failures == 0
        return ctx

    async def exit_gate(self, ctx: StageContext) -> GateResult:
        s = self.stage_name
        if ctx.output_data.get("critical_failures", 1) > 0:
            return GateResult(gate_name="validation_exit", passed=False,
                              reason=f"Critical failures: {ctx.output_data['critical_failures']}")
        ctx.validations.append(
            _val("final_sign_off",
                 True,
                 "Ambiguous requirement scenario complete. "
                 "Zero silent inventions. All scope items sourced. "
                 "Normalised requirement approved by human.",
                 s))
        return GateResult(gate_name="validation_exit", passed=True)

    async def rollback(self, ctx: StageContext) -> StageContext:
        ctx.rollback_performed = True
        return ctx


